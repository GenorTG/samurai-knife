#!/usr/bin/env python3
"""Regenerates src/lib/nosql/redis-commands.data.ts from the official Redis command metadata.

Source: https://github.com/redis/docs/blob/main/data/commands.json (the data behind https://redis.io/docs/latest/commands/).
Usage:  python3 -I scripts/gen-redis-commands.py [path/to/commands.json]   (downloads it when no path is given)
Keeps core (non-module) command groups only; arguments are compacted to {n,t,k,o,m,mt,a}.
"""
import json
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/redis/docs/main/data/commands.json"
GROUPS = {"string", "hash", "list", "set", "sorted-set", "stream", "generic", "pubsub", "transactions", "hyperloglog", "bitmap", "geo", "scripting", "connection", "server"}
OUT = Path(__file__).resolve().parent.parent / "src/lib/nosql/redis-commands.data.ts"


def compact_arg(arg):
    out = {"n": arg["name"], "t": arg["type"]}
    if arg.get("token"):
        out["k"] = arg["token"]
    if arg.get("optional"):
        out["o"] = 1
    if arg.get("multiple"):
        out["m"] = 1
    if arg.get("multiple_token"):
        out["mt"] = 1
    if arg.get("arguments"):
        out["a"] = [compact_arg(a) for a in arg["arguments"]]
    return out


def main():
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(URL) as resp:
            data = json.load(resp)
    rows = []
    for name, meta in sorted(data.items()):
        if meta.get("group") not in GROUPS or "arity" not in meta:
            continue
        row = {
            "name": name,
            "group": meta["group"],
            "arity": meta["arity"],
            "since": meta.get("since", ""),
            "complexity": meta.get("complexity", ""),
            "summary": meta.get("summary", ""),
            "cats": [c.lstrip("@") for c in meta.get("acl_categories", [])],
            "args": [compact_arg(a) for a in meta.get("arguments", [])],
        }
        if meta.get("deprecated_since"):
            row["deprecated"] = meta["deprecated_since"]
            row["replacedBy"] = meta.get("replaced_by", "").replace("`", "")
        rows.append(row)
    lines = ",\n".join("  " + json.dumps(r, separators=(",", ":"), ensure_ascii=False) for r in rows)
    OUT.write_text(
        "// GENERATED by scripts/gen-redis-commands.py from https://github.com/redis/docs (data/commands.json). Do not edit by hand.\n"
        "import type { RedisCommandDef } from \"./redis-types\";\n\n"
        f"export const REDIS_COMMAND_DATA: RedisCommandDef[] = [\n{lines},\n];\n"
    )
    print(f"{len(rows)} commands -> {OUT}")


if __name__ == "__main__":
    main()
