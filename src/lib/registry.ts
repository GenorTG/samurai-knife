export type ToolFamily = (typeof TOOL_FAMILIES)[number]["id"];

/** One tab of a suite. `component` is the key in `src/tools/registry-client.tsx`. */
export interface ToolTab {
  /** Value of the `?tab=` query parameter. Keep stable: it is a bookmark. */
  id: string;
  label: string;
  /** Component key; it is the slug the tool had before it was folded in. */
  component: string;
  /** Tab content needs the full viewport width (for example a page editor). */
  wide?: boolean;
}

/** Where a retired standalone slug now lives. */
export interface SlugAlias {
  slug: string;
  tab?: string;
}

export interface ToolMeta {
  /** URL segment and component key. Keep stable: it is a bookmark. */
  slug: string;
  name: string;
  /** One line, verb-first, says exactly what it does. */
  tagline: string;
  category: ToolCategory;
  /** Fine-grained discovery facet. Keep labels in TOOL_FAMILIES. */
  family: ToolFamily;
  kind: ToolKind;
  /** Extra search terms: synonyms, file types, verbs people type. */
  keywords: string[];
  /**
   * Present on suites: one entry per tab, first tab is the default. The suite
   * renders each tab's component lazily instead of a single component.
   */
  tabs?: ToolTab[];
  /** Sidecar service (src/lib/services/definitions.ts) the tool needs; it shows an install card until it is installed. */
  sidecar?: string;
}

