export const TOOL_BY_SLUG: ReadonlyMap<string, ToolMeta> = new Map(
  TOOLS.map((tool) => [tool.slug, tool]),
);

export function findTool(slug: string): ToolMeta | undefined {
  return TOOL_BY_SLUG.get(slug);
}

/** Alias target for a retired slug, or undefined for live or unknown slugs. */
export function resolveAlias(slug: string): SlugAlias | undefined {
  if (TOOL_BY_SLUG.has(slug)) return undefined;
  return Object.hasOwn(SLUG_ALIASES, slug) ? SLUG_ALIASES[slug] : undefined;
}

/** Maps a stored or typed slug (possibly retired) to the live registry slug. */
export function canonicalSlug(slug: string): string {
  return resolveAlias(slug)?.slug ?? slug;
}

/**
 * The tab a retired slug lands on: the requested one when the target suite has it (a merged suite keeps the old
 * suite's tab ids, so `/tools/css-grid?tab=clamp` opens `/tools/css?tab=clamp`), else the alias's own tab.
 */
export function aliasTab(slug: string, requestedTab?: string | null): string | undefined {
  const alias = resolveAlias(slug);
  if (!alias) return requestedTab ?? undefined;
  if (requestedTab && findTool(alias.slug)?.tabs?.some((tab) => tab.id === requestedTab)) return requestedTab;
  return alias.tab;
}

/** Route for a slug, including the tab for retired slugs (and the requested tab, when the target has it). */
export function toolHref(slug: string, requestedTab?: string | null): string {
  const alias = resolveAlias(slug);
  if (!alias) return requestedTab ? `/tools/${slug}?tab=${encodeURIComponent(requestedTab)}` : `/tools/${slug}`;
  const tab = aliasTab(slug, requestedTab);
  return tab ? `/tools/${alias.slug}?tab=${encodeURIComponent(tab)}` : `/tools/${alias.slug}`;
}

export function categoryLabel(id: ToolCategory): string {
  return CATEGORIES.find((c) => c.id === id)?.label ?? id;
}

export function familyLabel(id: ToolFamily): string {
  return TOOL_FAMILIES.find((family) => family.id === id)?.label ?? id;
}

/**
 * Ranked search over name, tagline and keywords. Exact-name hits first, then
 * prefix, then substring, then keyword/tagline. Good enough and dependency-free.
 */
export function searchTools(query: string, pool: ToolMeta[] = TOOLS): ToolMeta[] {
  const q = query.trim().toLowerCase();
  if (!q) return pool;

  const terms = q.split(/\s+/).filter(Boolean);
  const scored: { tool: ToolMeta; score: number }[] = [];

  for (const tool of pool) {
    const name = tool.name.toLowerCase();
    const tag = tool.tagline.toLowerCase();
    const family = familyLabel(tool.family).toLowerCase();
    const keys = tool.keywords.map((k) => k.toLowerCase());
    const hay = `${name} ${tag} ${family} ${keys.join(" ")}`;

    if (!terms.every((t) => hay.includes(t))) continue;

    let score = 0;
    for (const t of terms) {
      if (name === t) score += 100;
      else if (name.startsWith(t)) score += 60;
      else if (name.includes(t)) score += 40;
      else if (family === t) score += 35;
      else if (family.startsWith(t)) score += 18;
      else if (keys.some((k) => k === t)) score += 30;
      else if (keys.some((k) => k.startsWith(t))) score += 20;
      else if (tag.includes(t)) score += 10;
      else score += 5;
    }
    scored.push({ tool, score });
  }

  return scored
    .sort((a, b) => b.score - a.score || a.tool.name.localeCompare(b.tool.name))
    .map((s) => s.tool);
}

/** Strict search first; if nothing matches every term, rank by how many terms match (for agent and MCP callers). */
export function searchToolsLoose(query: string, pool: ToolMeta[] = TOOLS): ToolMeta[] {
  const strict = searchTools(query, pool);
  if (strict.length > 0 || !query.trim()) return strict;
  const scores = new Map<ToolMeta, number>();
  for (const term of query.toLowerCase().split(/\s+/).filter((t) => t.length > 2)) {
    for (const tool of searchTools(term, pool)) scores.set(tool, (scores.get(tool) ?? 0) + 1);
  }
  return Array.from(scores.entries()).sort((a, b) => b[1] - a[1]).map(([tool]) => tool);
}
