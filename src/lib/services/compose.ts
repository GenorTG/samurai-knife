import { stringify } from "yaml";
import { composeProject, type SidecarDefinition } from "./definitions";

/**
 * Pure compose rendering: definition + install choices -> compose.yaml text. No I/O, unit-tested
 * (tests/services.test.mjs). The published port is always bound to one concrete address (KNIFE_HOST), never every
 * interface: the same rule the app itself follows. Every container drops all capabilities except the definition's
 * `security.capAdd`, runs with `no-new-privileges` and a pids cap (host audit M2).
 */

export const SECRETS_FILE = "secrets.env";
/** Folder next to compose.yaml that holds a definition's `assets` (relative bind mounts resolve against it). */
export const ASSETS_DIR = "assets";
export const LABEL_PREFIX = "dev.samurai-knife";
/** pids_limit when a definition sets none: a fork bomb in a container stops there instead of exhausting the host. */
export const DEFAULT_PIDS_LIMIT = 512;
const CAPABILITY = /^[A-Z][A-Z0-9_]{1,31}$/;

const WILDCARD = /^(?:0\.0\.0\.0|0|::|\[::\]|::ffff:0\.0\.0\.0|\*)?$/i;

export class ComposeError extends Error {}

export interface ComposeChoices {
  bindHost: string;
  hostPort: number;
  /** Image actually installed (normally the definition's pin). */
  image?: string;
  /** Environment computed from the install (e.g. the request-filter allow list); added after the definition's env. */
  extraEnv?: Record<string, string>;
}

/**
 * The ONLYOFFICE/Euro-Office request filter (`services.CoAuthoring.request-filtering-agent`) as a NODE_CONFIG override:
 * node-config applies it after the image's local.json, and supervisord passes the container env to docservice and
 * converter. `allowIPAddressList` is matched against the resolved address exactly.
 */
export function onlyofficeFilterEnv(allowIps: readonly string[]): Record<string, string> {
  const filter = { allowPrivateIPAddress: false, allowMetaIPAddress: false, allowIPAddressList: [...new Set(allowIps)] };
  return { NODE_CONFIG: JSON.stringify({ services: { CoAuthoring: { "request-filtering-agent": filter } } }) };
}

export function isWildcardHost(host: string): boolean {
  return WILDCARD.test(host.trim());
}

/** `host:port:container` with IPv6 literals bracketed, as compose expects. */
export function portMapping(bindHost: string, hostPort: number, containerPort: number): string {
  const host = bindHost.includes(":") && !bindHost.startsWith("[") ? `[${bindHost}]` : bindHost;
  return `${host}:${hostPort}:${containerPort}`;
}

export function renderCompose(def: SidecarDefinition, choices: ComposeChoices): string {
  if (isWildcardHost(choices.bindHost)) {
    throw new ComposeError(`refusing to publish ${def.id} on "${choices.bindHost || "(empty)"}": bind to one address (KNIFE_HOST), never every interface.`);
  }
  if (!Number.isInteger(choices.hostPort) || choices.hostPort < 1 || choices.hostPort > 65535) {
    throw new ComposeError(`invalid host port ${choices.hostPort}`);
  }
  const service: Record<string, unknown> = {
    image: choices.image ?? def.image,
    // Lifecycle belongs to the app (lazy start, idle stop): no restart policy, so a reboot does not bring it back.
    restart: "no",
    ports: [portMapping(choices.bindHost, choices.hostPort, def.containerPort)],
    env_file: [SECRETS_FILE],
    environment: { ...def.env, ...(choices.extraEnv ?? {}) },
    // Lets the container reach the host as host.docker.internal (an alternative app URL, see docs/SIDECARS.md).
    extra_hosts: ["host.docker.internal:host-gateway"],
    volumes: [
      ...def.volumes.map((volume) => `${volume.name}:${volume.target}`),
      ...(def.assets ? [`./${ASSETS_DIR}:${def.assets.target}:ro`] : []),
    ],
    labels: {
      [`${LABEL_PREFIX}.managed`]: "true",
      [`${LABEL_PREFIX}.service`]: def.id,
    },
  };
  if (def.memLimit) service.mem_limit = def.memLimit;
  if (def.cpus) service.cpus = def.cpus;
  Object.assign(service, securityOptions(def));
  const doc = {
    name: composeProject(def.id),
    services: { [def.serviceName]: service },
    volumes: Object.fromEntries(def.volumes.map((volume) => [volume.name, { labels: { [`${LABEL_PREFIX}.service`]: def.id } }])),
  };
  return `# Generated by Smart Knife (src/lib/services/compose.ts). Edits are overwritten on install/update.\n${stringify(doc)}`;
}

/** cap_drop / cap_add / security_opt / pids_limit for a definition; refuses malformed capability names. */
export function securityOptions(def: SidecarDefinition): Record<string, unknown> {
  const capAdd = [...new Set(def.security.capAdd.map((cap) => cap.trim().toUpperCase().replace(/^CAP_/, "")))];
  const bad = capAdd.find((cap) => !CAPABILITY.test(cap) || cap === "ALL");
  if (bad !== undefined) throw new ComposeError(`${def.id}: invalid capability "${bad}"`);
  const pids = def.security.pidsLimit ?? DEFAULT_PIDS_LIMIT;
  if (!Number.isInteger(pids) || pids < 16) throw new ComposeError(`${def.id}: pids limit must be an integer >= 16`);
  return {
    cap_drop: ["ALL"],
    ...(capAdd.length ? { cap_add: capAdd.sort() } : {}),
    security_opt: ["no-new-privileges:true"],
    pids_limit: pids,
  };
}

/** secrets.env body: KEY=value lines. Values are hex, so no quoting is needed. */
export function renderSecrets(values: Record<string, string>): string {
  for (const [key, value] of Object.entries(values)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(key) || !/^[A-Za-z0-9_-]+$/.test(value)) throw new ComposeError(`unsafe secret entry ${key}`);
  }
  return `${Object.entries(values).map(([key, value]) => `${key}=${value}`).join("\n")}\n`;
}

export function parseSecrets(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split(/\r?\n/)) {
    const match = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line.trim());
    if (match) out[match[1]] = match[2];
  }
  return out;
}
