#!/usr/bin/env python3
"""Regenerate duckdb_functions.txt from a DuckDB build: `<python with duckdb + sqlglot> gen_duckdb_functions.py`.

The list is the authority for `duckdb_missing_functions` (like PRAGMA function_list for SQLite). It is the union of
duckdb_functions() (scalar, aggregate, macro, table functions) and every sqlglot function name DuckDB accepts when called
(`SELECT name()` fails with a binder error, not a Catalog Error): that catches parser-level aliases such as IFNULL that
duckdb_functions() does not list. The running engine never imports duckdb; only this generator does."""
from pathlib import Path

import duckdb
from sqlglot import exp

con = duckdb.connect()
names = {row[0].lower() for row in con.execute("SELECT DISTINCT function_name FROM duckdb_functions()").fetchall() if row[0].isidentifier()}
probe = {key.lower() for key in exp.FUNCTION_BY_NAME if key.isidentifier()}
for name in sorted(probe - names):
    try:
        con.execute(f"SELECT {name}()")
        names.add(name)  # a call with no arguments succeeded
    except duckdb.CatalogException:
        pass  # "Scalar Function with name X does not exist"
    except Exception:
        names.add(name)  # binder/parser/argument error: the function exists
out = Path(__file__).with_name("duckdb_functions.txt")
out.write_text(f"# DuckDB {duckdb.__version__} function names (generated by gen_duckdb_functions.py)\n" + "\n".join(sorted(names)) + "\n")
print(len(names), "names ->", out)
